"""Generates the hidden acceptance corpus (E3) from a single source of
truth: TESTS below. Run this to regenerate corpus/*.bract and
corpus/manifest.json after editing a test's source or expectations here --
never hand-edit the generated .bract files or manifest.json directly.

Every test's expected outcome is derived by hand from DESIGN.md, not by
running any implementation -- see the "self-verifying" pattern used
throughout: a test computes a value and, only if it's wrong, deliberately
triggers `1 / 0` (a pinned, unambiguous `line N: division by zero` /
exit 1 signal). A clean pass is therefore always exit 0 with empty
stdout/stderr, which sidesteps the fact that `bract run` has no print
facility to observe values with directly. Error-condition tests (lex/parse/
runtime traps) are direct: the program itself is the malformed/erroring
input, checked against DESIGN.md's pinned message text where the spec
pins one, or checked by exit code (+ `line N:` prefix) only where it
doesn't.
"""
