def main():
    corpus_dir = HERE
    manifest = []
    seen_ids = set()
    for t in TESTS:
        if t["id"] in seen_ids:
            raise SystemExit(f"duplicate test id: {t['id']}")
        seen_ids.add(t["id"])

        filename = t["id"].replace("-", "_") + ".bract"
        (corpus_dir / filename).write_text(t["source"])

        manifest.append(
            {
                "id": t["id"],
                "file": filename,
                "feature_area": t["feature_area"],
                "trap": t["trap"],
                "expected_exit_code": t["exit_code"],
                "expected_stdout": "",
                "stderr_check": t["stderr"],
                "expected_stderr": t["stderr_text"],
            }
        )

    (corpus_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n"
    )
    n_traps = sum(1 for t in TESTS if t["trap"])
    print(f"generated {len(TESTS)} corpus programs ({n_traps} prior-trap) into {corpus_dir}")


if __name__ == "__main__":
    main()
